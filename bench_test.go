// requireRealAllocator steps aside when the race detector is on, because it
// tracks every allocation: the counts it produces describe a build nobody ships,
// and a budget is a statement about a build somebody does.
func requireRealAllocator(t *testing.T) {
	t.Helper()

	if synth.RaceEnabled {
		t.Skip("allocation counts are not meaningful under the race detector")
	}
}

// Allocation budgets. A benchmark tells you what a path costs today; a budget
// tells you when it got worse, which is the failure that otherwise goes
// unnoticed until someone profiles a terminal.
//
// Each ceiling is the baseline as measured here plus room for a different
// allocator, not a target: these describe what the code does today, so that a
// change which doubles the garbage per frame has to argue for itself. The
// measurement each one rests on is printed by the test that uses it.
//
// FrameAt allocates a cell buffer per frame and should: a frame from it belongs
// to the caller and must outlive the next call. Keyframes() rescans every frame's
// flags on each call and so rebuilds its list. Both are per-frame costs, and a
// seek pays each of them once for every frame it replays.
const (
	parseBudgetBytes    = 400 << 10
	parseBudgetAllocs   = 20
	frameAtBudgetBytes  = 160 << 10
	frameAtBudgetAllocs = 24
	keyframesBudget     = 8 << 10
	keyframesAllocs     = 3
)

func TestParseAllocationBudget(t *testing.T) {
	requireRealAllocator(t)

	c := videoCorpus(t)

	allocs, bytes := synth.Measure(5, func() {
		anim, err := Parse(c.blob)
		if err != nil {
			t.Fatal(err)
		}
		synth.Sink = anim
	})
	t.Logf("Parse: %.0f allocs/op, %.1f KB/op for %d KB of input", allocs, bytes/1024, len(c.blob)/1024)

	if allocs > parseBudgetAllocs {
		t.Errorf("Parse allocates %.0f times, over the %d budget", allocs, parseBudgetAllocs)
	}
	if bytes > parseBudgetBytes {
		t.Errorf("Parse allocates %.1f KB, over the %.1f KB budget", bytes/1024, float64(parseBudgetBytes)/1024)
	}
}

func TestFrameAtAllocationBudget(t *testing.T) {
	requireRealAllocator(t)

	anim := videoCorpus(t).anim
	count := anim.FrameCount()

	allocs, bytes := synth.Measure(50, func() {
		for i := range count / 50 {
			frame, err := anim.FrameAt(i % count)
			if err != nil {
				t.Fatal(err)
			}
			synth.Sink = frame
		}
	})
	perFrame := float64(count/50) + 1
	t.Logf("FrameAt: %.1f allocs/frame, %.1f KB/frame", allocs/perFrame, bytes/perFrame/1024)

	if got := allocs / perFrame; got > frameAtBudgetAllocs {
		t.Errorf("FrameAt allocates %.0f times per frame, over the %d budget", got, frameAtBudgetAllocs)
	}
	if got := bytes / perFrame; got > frameAtBudgetBytes {
		t.Errorf("FrameAt allocates %.1f KB per frame, over the %.1f KB budget",
			got/1024, float64(frameAtBudgetBytes)/1024)
	}
}

func TestKeyframesAllocationBudget(t *testing.T) {
	requireRealAllocator(t)

	anim := videoCorpus(t).anim

	allocs, bytes := synth.Measure(20, func() {
		synth.SinkInts = anim.Keyframes()
	})
	t.Logf("Keyframes: %.1f allocs/op, %.1f KB/op", allocs, bytes/1024)

	if allocs > keyframesAllocs {
		t.Errorf("Keyframes allocates %.0f times, over the %d budget", allocs, keyframesAllocs)
	}
	if bytes > keyframesBudget {
		t.Errorf("Keyframes allocates %.1f KB, over the %.1f KB budget",
			bytes/1024, float64(keyframesBudget)/1024)
	}
}
