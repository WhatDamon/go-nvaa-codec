// The synthetic corpus exists because the committed animations are tiny -- the
// largest is 6 KB -- and seeking, decoding and parsing all behave differently at
// real sizes. Building it once per test binary keeps the setup cost out of every
// measurement. See internal/synth for what the files contain and why.
type corpus struct {
	blob []byte
	anim *Animation
}

var (
	videoOnce   = sync.OnceValues(func() (corpus, error) { return buildCorpus(synth.VideoCorpus) })
	longGOPOnce = sync.OnceValues(func() (corpus, error) { return buildCorpus(synth.LongGOPCorpus) })
)

func buildCorpus(load func() (synth.Corpus, error)) (corpus, error) {
	built, err := load()
	if err != nil {
		return corpus{}, err
	}
	anim, err := Parse(built.Blob)
	if err != nil {
		return corpus{}, fmt.Errorf("parsing the synthetic corpus: %w", err)
	}
	return corpus{blob: built.Blob, anim: anim}, nil
}

func corpusFrom(tb testing.TB, load func() (corpus, error)) corpus {
	tb.Helper()
	loaded, err := load()
	if err != nil {
		tb.Fatal(err)
	}
	return loaded
}

func videoCorpus(tb testing.TB) corpus   { return corpusFrom(tb, videoOnce) }
func longGOPCorpus(tb testing.TB) corpus { return corpusFrom(tb, longGOPOnce) }

// heaviestGOP is the span a seek has to replay when it rewinds as far as the
// encoder allows: the longest run of frames between one keyframe and the next.
func heaviestGOP(anim *Animation) (start, end int) {
	keyframes := anim.Keyframes()
	start, end = 0, anim.FrameCount()
	for i, k := range keyframes {
		next := anim.FrameCount()
		if i+1 < len(keyframes) {
			next = keyframes[i+1]
		}
		if next-k > end-start {
			start, end = k, next
		}
	}
	return start, end
}

// readAnim reads a file from disk, failing the benchmark rather than returning
// an error: a benchmark whose subject is missing has nothing to report.
func readAnim(tb testing.TB, path string) *Animation {
	tb.Helper()

	anim, err := ReadFile(path)
	if err != nil {
		tb.Fatal(err)
	}
	return anim
}

