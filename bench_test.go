// BenchmarkParseReal measures parsing footage the synthetic corpus only imitates.
//
// The artifacts are generated by a separate project and are not committed, so a
// checkout without them skips. The parent line that appears above the per-file
// sub-benchmarks is the discovery loop, not a measurement.
func BenchmarkParseReal(b *testing.B) {
	paths := synth.Artifacts("../artifacts", "../../artifacts")
	if len(paths) == 0 {
		b.Skip("no artifacts/ directory in this checkout")
	}

	for _, path := range paths {
		b.Run(filepath.Base(path), func(b *testing.B) {
			blob, err := os.ReadFile(path)
			if err != nil {
				b.Fatal(err)
			}
			b.SetBytes(int64(len(blob)))
			b.ReportAllocs()
			b.ResetTimer()

			for range b.N {
				anim, err := Parse(blob)
				if err != nil {
					b.Fatal(err)
				}
				synth.Sink = anim
			}
		})
	}
}

func BenchmarkFrameAt(b *testing.B) {
	anim := videoCorpus(b).anim
	picks := synth.Targets(anim.FrameCount(), 1024)
	b.ReportAllocs()
	b.ResetTimer()

	for i := 0; b.Loop(); i++ {
		frame, err := anim.FrameAt(picks[i%len(picks)])
		if err != nil {
			b.Fatal(err)
		}
		synth.Sink = frame
	}
}

// BenchmarkFrameAtHeaviestGOP is the inner loop of a rewind: every frame of the
// longest span a seek can be asked to replay, in order.
func BenchmarkFrameAtHeaviestGOP(b *testing.B) {
	anim := longGOPCorpus(b).anim
	start, end := heaviestGOP(anim)
	b.ReportAllocs()
	b.ResetTimer()

	for i := 0; b.Loop(); i++ {
		frame, err := anim.FrameAt(start + i%(end-start))
		if err != nil {
			b.Fatal(err)
		}
		synth.Sink = frame
	}
}

