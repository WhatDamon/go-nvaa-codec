// BenchmarkHeaders is the walk Parse already paid for: it should read no
// payload, so its cost is the per-frame bookkeeping and nothing else.
func BenchmarkHeaders(b *testing.B) {
	anim := videoCorpus(b).anim
	b.ReportAllocs()
	b.ResetTimer()

	for range b.N {
		total := 0
		for header := range anim.Headers() {
			total += header.PayloadLength
		}
		synth.SinkInt = total
	}
}

